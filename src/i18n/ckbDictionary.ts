/**
 * Resolves an Arabic UI phrase into Central Kurdish (Sorani) if available.
 * Also handles phrases ending with `:`, `...`, `…`, or leading `+ `.
 */
export function translateToKurdish(arText: string | undefined | null): string | undefined {
  if (!arText) return undefined;
  const trimmed = arText.trim();
  if (!trimmed) return undefined;

  if (CKB_DICTIONARY[trimmed]) {
    return CKB_DICTIONARY[trimmed];
  }

  if (trimmed.endsWith(':')) {
    const withoutColon = trimmed.slice(0, -1).trim();
    if (CKB_DICTIONARY[withoutColon]) {
      return `${CKB_DICTIONARY[withoutColon]}:`;
    }
  }

  if (trimmed.endsWith('...') || trimmed.endsWith('…')) {
    const suffix = trimmed.endsWith('...') ? '...' : '…';
    const withoutEllipsis = trimmed.slice(0, -suffix.length).trim();
    if (CKB_DICTIONARY[withoutEllipsis]) {
      return `${CKB_DICTIONARY[withoutEllipsis]}${suffix}`;
    }
  }

  if (trimmed.startsWith('+ ')) {
    const withoutPlus = trimmed.slice(2).trim();
    if (CKB_DICTIONARY[withoutPlus]) {
      return `+ ${CKB_DICTIONARY[withoutPlus]}`;
    }
  }

  return undefined;
}
